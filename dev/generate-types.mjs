// GraphQL

const GRAPHQL_SCALARS = {
  String: 'string',
  ID: 'string',
  Date: 'string',
  Int: 'int',
  Float: 'double',
  Boolean: 'bool',
  Upload: 'object',
}

const VALUE_TYPES = new Set(['int', 'double', 'bool'])

// The C# type (without its trailing `?`) of a GraphQL type. `json` is what the
// JSON scalar becomes: JToken in a response, object in something that is sent.
function graphqlType(type, json) {
  if (isNonNullType(type)) return graphqlType(type.ofType, json)
  if (isListType(type)) {
    const inner = graphqlType(type.ofType, json)
    const nullable = !isNonNullType(type.ofType)
    return `List<${inner}${nullable ? '?' : ''}>`
  }
  if (isScalarType(type)) {
    if (type.name === 'JSON') return json
    const mapped = GRAPHQL_SCALARS[type.name]
    if (!mapped) throw new Error(`Unexpected scalar ${type.name}`)
    return mapped
  }
  return type.name
}

function graphqlDefault(value) {
  return JSON.stringify(value)
}

function generateGraphql(schema) {
  const dir = path.join(TYPES_DIR, 'GraphQL')
  clean(dir)
  const usings = ['System', 'System.Collections.Generic', 'Newtonsoft.Json', 'Newtonsoft.Json.Linq']
  const roots = new Set([schema.getQueryType()?.name, schema.getMutationType()?.name])
  const names = []
  for (const type of Object.values(schema.getTypeMap())) {
    if (type.name.startsWith('__') || roots.has(type.name)) continue
    if (!isObjectType(type) && !isInputObjectType(type)) continue

    const isInput = isInputObjectType(type)
    const cls = new ClassBuilder(type.name, { description: type.description })
    for (const field of Object.values(type.getFields())) {
      const descriptions = [field.description?.trim()].filter(Boolean)
      if (isInput && field.defaultValue !== undefined) {
        descriptions.push(`Defaults to \`${graphqlDefault(field.defaultValue)}\` when left out.`)
      }
      cls.addProperty({
        jsonName: field.name,
        type: graphqlType(field.type, isInput ? 'object' : 'JToken'),
        description: descriptions.join('\n\n'),
        required: isInput && isNonNullType(field.type) && field.defaultValue === undefined,
        deprecated: field.deprecationReason ?? null,
      })
    }
    writeFile(dir, type.name, SCHEMA_SOURCE, 'Anvil.Types.GraphQL', usings, [cls])
    names.push(type.name)
  }
  return names
}

function generateOperations(schema) {
  const dir = path.join(TYPES_DIR, 'Operations')
  clean(dir)
  const usings = ['System', 'System.Collections.Generic', 'Anvil.Types.GraphQL', 'Newtonsoft.Json']
  const operationNames = { Queries: [], Mutations: [] }
  const seen = new Set()
  for (const [kind, rootType] of [
    ['query', schema.getQueryType()],
    ['mutation', schema.getMutationType()],
  ]) {
    if (!rootType) continue
    for (const field of Object.values(rootType.getFields())) {
      const className = `${pascal(field.name)}Args`
      if (seen.has(className)) throw new Error(`${className} would be both a query and a mutation`)
      seen.add(className)
      operationNames[kind === 'query' ? 'Queries' : 'Mutations'].push(field.name)

      const returns = graphqlType(field.type, 'JToken')
      const description = [`Arguments of the \`${field.name}\` ${kind}, which returns \`${returns}\`.`, field.description?.trim()]
        .filter(Boolean)
        .join('\n\n')
      const cls = new ClassBuilder(className, { description })
      for (const arg of field.args) {
        const descriptions = [arg.description?.trim()].filter(Boolean)
        if (arg.defaultValue !== undefined) {
          descriptions.push(`Defaults to \`${graphqlDefault(arg.defaultValue)}\` when left out.`)
        }
        cls.addProperty({
          jsonName: arg.name,
          type: graphqlType(arg.type, 'object'),
          description: descriptions.join('\n\n'),
          required: isNonNullType(arg.type) && arg.defaultValue === undefined,
          deprecated: arg.deprecationReason ?? null,
        })
      }
      writeFile(dir, className, SCHEMA_SOURCE, 'Anvil.Types.Operations', usings, [cls])
    }
  }

  // The operation names, for tests and tooling that check every operation has its class
  const lines = header(SCHEMA_SOURCE)
  lines.push('using System.Collections.Generic;', '', 'namespace Anvil.Types.Operations', '{')
  lines.push(`${INDENT}/// <summary>The names of every query and mutation in the Anvil GraphQL schema.</summary>`)
  lines.push(`${INDENT}public static class OperationNames`, `${INDENT}{`)
  for (const [kind, list] of Object.entries(operationNames)) {
    if (kind !== 'Queries') lines.push('')
    lines.push(`${INDENT}${INDENT}public static readonly IReadOnlyList<string> ${kind} = new[]`, `${INDENT}${INDENT}{`)
    for (const name of list) lines.push(`${INDENT}${INDENT}${INDENT}${csString(name)},`)
    lines.push(`${INDENT}${INDENT}};`)
  }
  lines.push(`${INDENT}}`, '}', '')
  writeFileSync(path.join(dir, 'OperationNames.cs'), lines.join('\n'))
  return operationNames
}

// ---------------------------------------------------------------------------
// OpenAPI

function refName(ref) {
  const match = /^#\/components\/schemas\/([A-Za-z0-9_]+)$/.exec(ref)
  if (!match) throw new Error(`Unsupported $ref ${ref}`)
  return match[1]
}

function isPrimitive(schema) {
  return ['string', 'number', 'integer', 'boolean'].includes(schema.type) && !schema.properties
}

function constraints(schema) {
  const notes = []
  if (schema.minimum != null && schema.maximum != null) notes.push(`Between ${schema.minimum} and ${schema.maximum}.`)
  else if (schema.minimum != null) notes.push(`At least ${schema.minimum}.`)
  else if (schema.maximum != null) notes.push(`At most ${schema.maximum}.`)
  if (schema.default !== undefined) notes.push(`Defaults to \`${JSON.stringify(schema.default)}\` when left out.`)
  return notes
}

function article(name) {
  return `${/^[AEIOU]/.test(name) ? 'an' : 'a'} ${name}`
}

// Describes a oneOf so the summary says what the `object` property accepts
function describeAlternatives(alternatives, classNames) {
  const parts = alternatives.map((alt, i) => {
    if (alt.$ref) return article(refName(alt.$ref))
    if (alt.enum) return alt.enum.map((v) => `\`${JSON.stringify(v)}\``).join(' or ')
    if (alt.type === 'object' && classNames[i]) return article(classNames[i])
    if (alt.type === 'array') return `a list of ${alt.items?.type === 'object' && classNames[i] ? classNames[i] : alt.items?.type ?? 'values'}`
    if (alt.type === 'object') return 'an object'
    return `a ${alt.type}`
  })
  return `One of: ${parts.join('; ')}.`
}

// The C# type of an OpenAPI schema, emitting nested classes into `file` as it
// goes. `owner` is the class the property is on and `jsonName` the property.
function restType(schema, owner, jsonName, file) {
  if (schema.$ref) return { type: refName(schema.$ref) }

  if (schema.oneOf) {
    // Alternatives that are objects get their own class; the property is `object`
    const classNames = []
    let count = 0
    for (const alt of schema.oneOf) {
      const objectSchema = alt.type === 'object' && alt.properties ? alt : alt.type === 'array' && alt.items?.type === 'object' && alt.items.properties ? alt.items : null
      if (objectSchema) {
        count += 1
        const name = `${owner.name}${pascal(alt.type === 'array' ? singular(jsonName) : jsonName)}${count > 1 ? count : ''}`
        buildRestClass(name, objectSchema, file)
        classNames.push(name)
      } else {
        classNames.push(null)
      }
    }
    return { type: 'object', note: describeAlternatives(schema.oneOf, classNames) }
  }

  switch (schema.type) {
    case 'string':
      if (schema.enum && schema.enum.every((v) => typeof v === 'string')) {
        owner.addEnumValues(jsonName, schema.enum)
        return { type: 'string', note: `See <see cref="${pascal(jsonName)}Values"/>.` }
      }
      return { type: 'string' }
    case 'integer':
      return { type: 'int' }
    case 'number':
      return { type: 'double' }
    case 'boolean':
      return { type: 'bool' }
    case 'array': {
      const items = schema.items ?? {}
      if (items.oneOf) {
        const classNames = []
        let count = 0
        for (const alt of items.oneOf) {
          if (alt.type === 'object' && alt.properties) {
            count += 1
            const name = `${owner.name}${pascal(singular(jsonName))}${count > 1 ? count : ''}`
            buildRestClass(name, alt, file)
            classNames.push(name)
          } else {
            classNames.push(null)
          }
        }
        return { type: 'List<object>', note: `Each item is ${describeAlternatives(items.oneOf, classNames).replace(/^One of: /, 'one of: ')}` }
      }
      const inner = restType(items, owner, singular(jsonName), file)
      const nullable = VALUE_TYPES.has(inner.type) || inner.type === 'object' ? '' : '?'
      return { type: `List<${inner.type}${nullable}>`, note: inner.note }
    }
    case 'object':
    default:
      if (schema.properties) {
        const name = `${owner.name}${pascal(jsonName)}`
        buildRestClass(name, schema, file)
        return { type: name }
      }
      if (schema.additionalProperties) {
        return { type: 'Dictionary<string, object>' }
      }
      return { type: 'object' }
  }
}

function buildRestClass(name, schema, file) {
  if (file.some((cls) => cls.name === name)) throw new Error(`${name} is generated twice`)
  const cls = new ClassBuilder(name, { description: schema.description })
  file.push(cls)
  const required = new Set(schema.required ?? [])
  for (const [jsonName, propSchema] of Object.entries(schema.properties ?? {})) {
    const { type, note } = restType(propSchema, cls, jsonName, file)
    const description = [propSchema.description?.trim(), note, ...constraints(propSchema)].filter(Boolean).join('\n\n')
    cls.addProperty({ jsonName, type, description, required: required.has(jsonName) })
  }
  return cls
}

function generateRest(spec) {
  const dir = path.join(TYPES_DIR, 'Rest')
  clean(dir)
  const usings = ['System', 'System.Collections.Generic', 'Newtonsoft.Json']
  const names = []
  for (const [name, schema] of Object.entries(spec.components?.schemas ?? {})) {
    const file = []
    buildRestClass(name, schema, file)
    // The named schema first, then the nested classes it needed
    writeFile(dir, name, OPENAPI_SOURCE, 'Anvil.Types.Rest', usings, file)
    names.push(name)
  }
  return names
}

// ---------------------------------------------------------------------------

function main() {
  const schema = buildSchema(readFileSync(SCHEMA_PATH, 'utf8'))
  const spec = JSON.parse(readFileSync(OPENAPI_PATH, 'utf8'))

  const rest = generateRest(spec)
  const graphql = generateGraphql(schema)
  const operations = generateOperations(schema)

  console.log(`Wrote ${rest.length} REST types, ${graphql.length} GraphQL types and ${operations.Queries.length + operations.Mutations.length} operation argument types to ${path.relative(root, TYPES_DIR)}`)
}

main()
