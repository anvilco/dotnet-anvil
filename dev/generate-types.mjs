// Generates src/Anvil/Types from the API specs that ship with the
// @anvilco/types dependency in dev/ (see dev/fetch-schema.sh):
//
// - Types/Rest/*.cs: the REST API's request bodies, from its openapi.json
//   (or schema/openapi.json while the installed version predates it).
// - Types/GraphQL/*.cs: every object and input type in its GraphQL schema.
// - Types/Operations/*.cs: the arguments of every query and mutation, e.g.
//   CreateEtchPacketArgs, from the same schema, plus OperationNames.
//
// Reads the installed package only, so this runs offline. dev/fetch-schema.sh
// is what bumps it.
//
// Every generated class is partial and extends Anvil.Types.GeneratedModel, so
// the hand-written payload types can extend them and unknown JSON members are
// kept. Enums become string properties with a nested *Values class of
// constants, so a value the API adds later is accepted rather than rejected.
//
// Usage: cd dev && npm ci && npm run generate
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { buildSchema, isInputObjectType, isListType, isNonNullType, isObjectType, isScalarType } from 'graphql'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)
const SCHEMA_PATH = require.resolve('@anvilco/types/schema.graphql')
const SCHEMA_VERSION = JSON.parse(readFileSync(path.join(path.dirname(SCHEMA_PATH), '..', 'package.json'), 'utf8')).version
// What the generated files say they came from
const SCHEMA_SOURCE = `@anvilco/types@${SCHEMA_VERSION} schema.graphql`
// Older versions of the package don't ship the OpenAPI spec; dev/fetch-schema.sh
// puts a copy from production in schema/ for them
const { OPENAPI_PATH, OPENAPI_SOURCE } = resolveOpenApi()

function resolveOpenApi() {
  try {
    return { OPENAPI_PATH: require.resolve('@anvilco/types/openapi.json'), OPENAPI_SOURCE: `@anvilco/types@${SCHEMA_VERSION} openapi.json` }
  } catch {
    const fallback = path.join(root, 'schema', 'openapi.json')
    return { OPENAPI_PATH: fallback, OPENAPI_SOURCE: path.relative(root, fallback) }
  }
}
const TYPES_DIR = path.join(root, 'src', 'Anvil', 'Types')

const INDENT = '    '

// Reserved by System.Object, so a property can't take the name
const OBJECT_MEMBERS = new Set(['Equals', 'GetHashCode', 'GetType', 'ToString', 'ReferenceEquals', 'MemberwiseClone'])

// ---------------------------------------------------------------------------
// Naming

// Splits camelCase into words, keeping acronyms and their plurals whole:
// webhookURL -> [webhook, URL], mergePDFs -> [merge, PDFs], base64File -> [base64, File]
function words(name) {
  return name
    .replace(/([A-Z]+)([A-Z][a-z]{2,})/g, '$1_$2')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .split(/[_\-\s]+/)
    .filter(Boolean)
}

function pascal(name) {
  return words(name)
    .map((word) => word[0].toUpperCase() + word.slice(1).toLowerCase())
    .join('')
}

function singular(name) {
  if (name.endsWith('ies')) return name.slice(0, -3) + 'y'
  if (name.endsWith('s') && !name.endsWith('ss')) return name.slice(0, -1)
  return name
}

// A property name that is legal in its class and unique among its siblings
function propertyName(jsonName, className, taken) {
  let name = pascal(jsonName)
  if (name === className || OBJECT_MEMBERS.has(name) || name === 'AdditionalData') name += 'Value'
  if (taken.has(name)) throw new Error(`${className} would have two properties named ${name}`)
  taken.add(name)
  return name
}

// ---------------------------------------------------------------------------
// Emitting C#

function escapeXml(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}

function summary(text, indent) {
  if (!text) return []
  const lines = text.trim().split('\n').map((line) => line.trimEnd())
  return [`${indent}/// <summary>`, ...lines.map((line) => `${indent}/// ${escapeXml(line)}`.trimEnd()), `${indent}/// </summary>`]
}

function csString(value) {
  return JSON.stringify(String(value))
}

function header(source) {
  return [
    '// <auto-generated>',
    `// Generated by dev/generate-types.mjs from ${source}. Do not edit by hand.`,
    '// Run `npm run generate` in dev/ to regenerate.',
    '// </auto-generated>',
    '#nullable enable',
    '',
  ]
}

class ClassBuilder {
  constructor(name, { description, base = 'GeneratedModel' } = {}) {
    this.name = name
    this.description = description
    this.base = base
    this.properties = []
    this.nested = []
    this.taken = new Set()
  }

  addProperty({ jsonName, type, description, required = false, deprecated = null }) {
    const name = propertyName(jsonName, this.name, this.taken)
    this.properties.push({ name, jsonName, type, description, required, deprecated })
  }

  // A nested static class of string constants for an enum property
  addEnumValues(jsonName, values) {
    const className = `${pascal(jsonName)}Values`
    if (this.nested.some((n) => n.className === className)) return
    this.nested.push({ className, jsonName, values })
  }

  lines(indent) {
    const out = []
    out.push(...summary(this.description, indent))
    out.push(`${indent}public partial class ${this.name} : ${this.base}`)
    out.push(`${indent}{`)
    const inner = indent + INDENT
    let first = true
    for (const nested of this.nested) {
      if (!first) out.push('')
      first = false
      out.push(`${inner}/// <summary>The values the API documents for <c>${nested.jsonName}</c>.</summary>`)
      out.push(`${inner}public static class ${nested.className}`)
      out.push(`${inner}{`)
      for (const value of nested.values) {
        out.push(`${inner}${INDENT}public const string ${pascal(value)} = ${csString(value)};`)
      }
      out.push(`${inner}}`)
    }
    for (const prop of this.properties) {
      if (!first) out.push('')
      first = false
      out.push(...summary(prop.description, inner))
      const options = [csString(prop.jsonName)]
      if (prop.required) options.push('Required = Required.Always')
      out.push(`${inner}[JsonProperty(${options.join(', ')})]`)
      if (prop.deprecated != null) out.push(`${inner}[Obsolete(${csString(prop.deprecated)})]`)
      out.push(`${inner}public ${prop.type}? ${prop.name} { get; set; }`)
    }
    out.push(`${indent}}`)
    return out
  }
}

function writeFile(dir, name, source, namespace, usings, classes) {
  const lines = header(source)
  for (const using of usings) lines.push(`using ${using};`)
  lines.push('', `namespace ${namespace}`, '{')
  classes.forEach((cls, i) => {
    if (i > 0) lines.push('')
    lines.push(...cls.lines(INDENT))
  })
  lines.push('}', '')
  mkdirSync(dir, { recursive: true })
  writeFileSync(path.join(dir, `${name}.cs`), lines.join('\n'))
}

function clean(dir) {
  mkdirSync(dir, { recursive: true })
  for (const file of readdirSync(dir)) {
    if (file.endsWith('.cs')) rmSync(path.join(dir, file))
  }
}

